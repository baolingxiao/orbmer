export const ENTITY_TYPES = new Set(Object.keys(ENTITY_FIELD_REGISTRY));

export function getEntityFields(entityType) {
  return ENTITY_FIELD_REGISTRY[entityType] || [];
}

export function getFieldConfig(entityType, fieldName) {
  return getEntityFields(entityType).find((row) => row.field === fieldName) || null;
}

export function assertFieldAllowed(entityType, fieldName) {
  if (!ENTITY_TYPES.has(entityType)) {
    const error = new Error(`Unsupported entityType: ${entityType}`);
    error.status = 400;
    error.code = "invalid_entity_type";
    throw error;
  }
  const cfg = getFieldConfig(entityType, fieldName);
  if (!cfg || !cfg.aiEnabled) {
    const error = new Error(`Field is not AI-enabled: ${fieldName}`);
    error.status = 400;
    error.code = "invalid_field";
    throw error;
  }
  return cfg;
}
